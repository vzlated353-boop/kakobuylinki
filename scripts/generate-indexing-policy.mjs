import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const __filename = fileURLToPath(import.meta.url)
const __dirname = path.dirname(__filename)
const root = path.resolve(__dirname, '..')
const auditPath = path.resolve(root, '..', 'kakobuylinki-content-audit', 'content-audit.json')
const policyPath = path.join(root, '.vitepress', 'indexing-policy.mjs')
const reportPath = path.resolve(root, '..', 'kakobuylinki-content-audit', 'indexing-policy-report.md')
const retainedComponentPages = new Set(['blog/about.md'])
const sourceExcludedBlogFiles = new Set([
  'blog/kakobuy-article-prompt.md',
  'blog/kakobuy-internal-link-rules.md',
  'blog/kakobuy-product-reference.md',
  'blog/kakobuy-review-report.md',
  'blog/kakobuy-topic-list.md',
  'blog/flexible-article-generator.md',
  'blog/topic-matrix.md',
  'blog/ideas.md',
  'blog/content-checklist.md',
  'blog/local-setup.md',
  'blog/product-workflow.md',
  'blog/website-structure.md',
])

if (!fs.existsSync(auditPath)) {
  throw new Error(`Missing content audit: ${auditPath}. Run pnpm audit:content first.`)
}

const audit = JSON.parse(fs.readFileSync(auditPath, 'utf8'))
const candidates = audit.pages
  .filter((page) => page.file.startsWith('blog/'))
  .filter((page) => !retainedComponentPages.has(page.file))
  .filter((page) => !sourceExcludedBlogFiles.has(page.file))
  .map((page) => {
    const reasons = []
    if (page.wordCount < 350) reasons.push('thin_content')
    if (page.replacementCharacterCount > 0) reasons.push('encoding_character')
    return { ...page, reasons }
  })
  .filter((page) => page.reasons.length > 0)
  .sort((a, b) => a.file.localeCompare(b.file))

const noindexFiles = new Set(candidates.map((page) => page.file))
const indexableBlogPaths = fs.readdirSync(path.join(root, 'blog'), { withFileTypes: true })
  .filter((entry) => entry.isFile() && entry.name.endsWith('.md'))
  .map((entry) => `blog/${entry.name}`)
  .filter((file) => !sourceExcludedBlogFiles.has(file))
  .filter((file) => !noindexFiles.has(file))
  .map((file) => `/${file.replace(/\.md$/, '')}`)
  .sort()

function collectFiles(directory, extensions) {
  return fs.readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const entryPath = path.join(directory, entry.name)
    if (entry.isDirectory()) return collectFiles(entryPath, extensions)
    return extensions.has(path.extname(entry.name)) ? [entryPath] : []
  })
}

const sourceFiles = [
  ...fs.readdirSync(root, { withFileTypes: true })
    .filter((entry) => entry.isFile() && entry.name.endsWith('.md'))
    .map((entry) => path.join(root, entry.name)),
  ...collectFiles(path.join(root, 'blog'), new Set(['.md'])),
  ...collectFiles(path.join(root, '.vitepress', 'theme'), new Set(['.vue', '.js', '.mjs'])),
]
const allBlogPaths = new Set(fs.readdirSync(path.join(root, 'blog'), { withFileTypes: true })
  .filter((entry) => entry.isFile() && entry.name.endsWith('.md'))
  .map((entry) => `blog/${entry.name}`)
  .filter((file) => !sourceExcludedBlogFiles.has(file))
  .map((file) => `/blog/${file.replace(/^blog\//, '').replace(/\.md$/, '')}`))
const missingBlogPaths = new Set()
for (const sourceFile of sourceFiles) {
  const content = fs.readFileSync(sourceFile, 'utf8')
  for (const match of content.matchAll(/\/blog\/[A-Za-z0-9][A-Za-z0-9._-]*(?:\/index)?(?=\/["'<\s]|["'<\s]|$)/g)) {
    const pagePath = match[0].replace(/\/index\/?$/, '').replace(/\/$/, '')
    if (!allBlogPaths.has(pagePath)) missingBlogPaths.add(pagePath)
  }
}
const orderedMissingBlogPaths = [...missingBlogPaths].sort()

const policy = `// Generated by scripts/generate-indexing-policy.mjs.\n// These URLs stay accessible to users and links, but are excluded from sitemap and carry noindex,follow until rewritten or repaired.\nexport const noindexRelativePaths = new Set([\n${candidates.map((page) => `  ${JSON.stringify(page.file)},`).join('\n')}\n])\n\nexport const noindexReasons = new Map([\n${candidates.map((page) => `  [${JSON.stringify(page.file)}, ${JSON.stringify(page.reasons.join(','))}],`).join('\n')}\n])\n\nexport const indexableBlogPaths = new Set([\n${indexableBlogPaths.map((pagePath) => `  ${JSON.stringify(pagePath)},`).join('\n')}\n])\n\nexport const missingBlogPaths = new Set([\n${orderedMissingBlogPaths.map((pagePath) => `  ${JSON.stringify(pagePath)},`).join('\n')}\n])\n`

const report = [
  '# 临时 noindex 候选清单',
  '',
  '该清单仅包含拥有客观质量信号的博客页面：正文过薄或含 UTF-8 替换字符（�）。页面仍可访问，且链接仍可被跟随；待完成实质重写或乱码修复后，可从政策文件移除并恢复至 sitemap。',
  '',
  `候选数量：**${candidates.length}**`,
  `站内引用但无对应页面的博客 URL：**${orderedMissingBlogPaths.length}**`,
  '',
  '| 页面 | 词数 | 质量信号 |',
  '| --- | ---: | --- |',
  ...candidates.map((page) => `| ${page.file} | ${page.wordCount} | ${page.reasons.join(', ')} |`),
  '',
].join('\n')

fs.writeFileSync(policyPath, policy)
fs.writeFileSync(reportPath, report)
console.log(`Generated noindex policy for ${candidates.length} blog page(s).`)
